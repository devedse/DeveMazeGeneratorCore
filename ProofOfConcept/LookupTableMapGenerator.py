class Maze:
    def __init__(self, width, height):
        self.width = width
        self.height = height
        # grid[y][x] stores the bitmask pointing toward the start. 0 = unvisited.
        self.grid = [[0 for _ in range(width)] for _ in range(height)]

    def get_passable_map(self, x, y):
        """
        Returns a 4-bit mask of neighbors that are inside bounds AND unvisited.
        This could be a lot more efficient.
        """
        mask = 0
        if y > 0 and self.grid[y-1][x] == 0: mask |= 1 # UP
        if x < self.width - 1 and self.grid[y][x+1] == 0: mask |= 2 # RIGHT
        if y < self.height - 1 and self.grid[y+1][x] == 0: mask |= 4 # DOWN
        if x > 0 and self.grid[y][x-1] == 0: mask |= 8 # LEFT
        return mask

    def set_back_direction(self, x, y, bit):
        self.grid[y][x] = bit

def generate_maze(width, height):
    maze = Maze(width, height)
    # Start at 0,0. Sentinel 15 marks the root.
    maze.grid[0][0] = 15 
    stack = [(0, 0)]
    while stack:
        x, y = stack[-1]
        mask = maze.get_passable_map(x, y)
        back_bits = BACK_BITS_TABLE[(mask << 3) + random.randrange(6)]
        if back_bits == 0:
            stack.pop()
        else:
            nx, ny = x + DX[back_bits], y + DY[back_bits]
            maze.grid[ny][nx] = back_bits
            stack.append((nx, ny))
    return maze

def solve_path(maze, end_x, end_y):
    path = set()
    cx, cy = end_x, end_y
    while maze.grid[cy][cx] != 15:
        path.add((cx, cy))
        b = maze.grid[cy][cx]
        cx += TRACE_DX[b]
        cy += TRACE_DY[b]
    path.add((cx, cy))
    return path

def draw_maze_with_walls(maze, path):
    # Expand the grid: each cell is 2x2 in the output
    render_w = maze.width * 2 + 1
    render_h = maze.height * 2 + 1
    
    # Initialize everything as a wall
    output = [["█" for _ in range(render_w)] for _ in range(render_h)]

    for y in range(maze.height):
        for x in range(maze.width):
            # Center of the cell in the expanded grid
            rx, ry = x * 2 + 1, y * 2 + 1
            
            # Open the cell itself
            output[ry][rx] = "·" if (x, y) in path else " "
            
            # Check the back-pointer to open a passage to the neighbor
            b = maze.grid[y][x]
            if b == 1: output[ry-1][rx] = " " # Passage UP
            if b == 2: output[ry][rx+1] = " " # Passage RIGHT
            if b == 4: output[ry+1][rx] = " " # Passage DOWN
            if b == 8: output[ry][rx-1] = " " # Passage LEFT

    # Print the resulting character grid
    for row in output:
        print("".join(row))

