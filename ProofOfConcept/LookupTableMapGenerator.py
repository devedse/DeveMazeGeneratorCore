# The stuff that actually matters.
#
# What we want to be able to do is go directly from the state of our
# neighbours and an RNG value to the location delta and the direction pointing
# back to the start.
#
# There are 16 possible states of our neighbours (4 bits, each representing 
# if that direction is occupied). For each of those possible states we will
# store a mapping from RNG to direction.  We need to handle having 1 2 or 3
# possible neighbours, so we actually use least common multiple (6).  This means
# we arent distorting the distribution.
#
# Rather than packing things as close as possible we align the table to
# multiples of 8, with the last 2 slots being invalid - never to be generated by
# the RNG.  We do this because to generate the offset into a flattened lookup
# table we need to multiply the neigbour mask by the number of choices.  If we
# packed everything tight this would be *6, but for a tiny bit of wasted space
# this becomes a *8 which can be implemented with a bit shift.
#
# At the index of the combined neighbour state and RNG value we store the chosen
# direction as a nibble (1 = UP, 2 = RIGHT, 4 = DOWN, 8 = LEFT, no valid
# direction is 0). Storing it like this allows us to directly index into the
# DX and DY value (or the reverse when we are tracing back to the start) while
# also handling dead ends.  Since no valid direction is zero we detect a dead
# end with a "branch if zero" which has its own efficient op in many
# architectures.  Obviously it is not so impactful in python, but this code is
# just for illustration.
#
# The lookup table is tiny and should almost certainly remain in whatever the
# lowest cache level is.
import random

# Translation arrays: Convert the direction back to the start into a forward-move
# delta.
DX = [0,  0, -1,  0,  0,  0,  0,  0,  1]
DY = [0,  1,  0,  0, -1,  0,  0,  0,  0]

# The inverse of the delta - Given a maze with the direction give the offset to
# the previous cell. Just DX and DY * -1.
TRACE_DX = [0, 0, 1, 0, 0, 0, 0, 0, -1]
TRACE_DY = [0, -1, 0, 0, 1, 0, 0, 0, 0]


def generate_back_bits_table():
    # The opposite of going up (1) is down (4), etc.  Only used for generating
    # the lookup table so a map is fine here.
    REVERSE = {1: 4, 2: 8, 4: 1, 8: 2}
    table = [0] * 128
    for mask in range(16):
        valid_bits = [b for b in [1, 2, 4, 8] if (mask & b)]
        if not valid_bits: continue
        base, num_valid = mask << 3, len(valid_bits)
        repeats = 6 // num_valid if num_valid <= 3 else 1
        choices = []
        for b in valid_bits: choices.extend([REVERSE[b]] * repeats)
        for i in range(min(6, len(choices))): table[base + i] = choices[i]
    return table

BACK_BITS_TABLE = generate_back_bits_table()

def move_randomly(maze, x, y):
    # This is the code we have optimised the hell out of because it runs
    # every step.
    #   - RNG does not depend on the number of neighbours.
    #   - Only a single bitshift and add to compute the next cell and
    #     the direction back towards the start.
    mask = maze.get_passable_map(x, y)
    idx = (mask << 3) + random.randrange(6)
    back_bits = BACK_BITS_TABLE[idx]
    return x + DX[back_bits], y + DY[back_bits], back_bits




